// ---- Round-trip: QsoToRecord → String → Parse → verify ----------------------

func TestRoundTrip_QsoToRecordStringParse(t *testing.T) {
	rec := Record{}
	rec.Call = "M0CMC"
	rec.Band = "40m"
	rec.Mode = "SSB"
	rec.Freq = "7050000" // Hz integer — formatField converts to MHz
	rec.QsoDate = "2025-05-08"
	rec.TimeOn = "08:45"
	rec.RstSent = "59"
	rec.RstRcvd = "59"
	rec.StationCallsign = "G4ABC"
	rec.Name = "Marc"
	rec.Comment = "Nice QSO"

	adifStr := rec.String()

	// Parse the serialised output back
	parsed, err := Parse([]byte(adifStr))
	if err != nil {
		t.Fatalf("Parse returned error: %v", err)
	}
	if len(parsed.Records) != 1 {
		t.Fatalf("got %d records, want 1", len(parsed.Records))
	}

	r := parsed.Records[0]

	// Verify fields survive the round-trip. Note: formatField normalises
	// dates (strip dashes), times (strip colons), and frequencies (Hz→MHz),
	// so the parsed values reflect the ADIF-canonical form, not the input.
	if r.Call != "M0CMC" {
		t.Fatalf("Call = %q, want %q", r.Call, "M0CMC")
	}
	if r.Band != "40m" {
		t.Fatalf("Band = %q, want %q", r.Band, "40m")
	}
	if r.Mode != "SSB" {
		t.Fatalf("Mode = %q, want %q", r.Mode, "SSB")
	}
	if r.QsoDate != "20250508" {
		t.Fatalf("QsoDate = %q, want %q", r.QsoDate, "20250508")
	}
	if r.TimeOn != "0845" {
		t.Fatalf("TimeOn = %q, want %q", r.TimeOn, "0845")
	}
	if r.RstSent != "59" {
		t.Fatalf("RstSent = %q, want %q", r.RstSent, "59")
	}
	if r.StationCallsign != "G4ABC" {
		t.Fatalf("StationCallsign = %q, want %q", r.StationCallsign, "G4ABC")
	}
	if r.Name != "Marc" {
		t.Fatalf("Name = %q, want %q", r.Name, "Marc")
	}
	if r.Comment != "Nice QSO" {
		t.Fatalf("Comment = %q, want %q", r.Comment, "Nice QSO")
	}

	// Freq: 7050000 → "7.050" (Hz to MHz conversion)
	if r.Freq != "7.050" {
		t.Fatalf("Freq = %q, want %q", r.Freq, "7.050")
	}
}

