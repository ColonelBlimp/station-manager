// ---- Parse: happy path with header and records ------------------------------

func TestParse_FullFileWithHeader(t *testing.T) {
	input := `Generated by test
<ADIF_VER:5>3.1.5
<CREATED_TIMESTAMP:16>20250508T120000Z
<PROGRAMID:2>SM
<PROGRAMVERSION:5>0.0.1
<EOH>
<CALL:5>M0CMC<BAND:3>40m<MODE:3>SSB<FREQ:5>7.050<QSO_DATE:8>20250508<TIME_ON:4>0845<RST_SENT:2>59<RST_RCVD:2>59<STATION_CALLSIGN:5>G4ABC<EOR>
<CALL:6>DL1ABC<BAND:3>20m<MODE:2>CW<QSO_DATE:8>20250509<TIME_ON:4>1430<EOR>
`
	adif, err := Parse([]byte(input))
	if err != nil {
		t.Fatalf("Parse returned error: %v", err)
	}

	// Header
	if adif.HeaderSection.ADIFVer != "3.1.5" {
		t.Fatalf("ADIFVer = %q, want %q", adif.HeaderSection.ADIFVer, "3.1.5")
	}
	if adif.HeaderSection.ProgramID != "SM" {
		t.Fatalf("ProgramID = %q, want %q", adif.HeaderSection.ProgramID, "SM")
	}
	if adif.HeaderSection.ProgramVersion != "0.0.1" {
		t.Fatalf("ProgramVersion = %q, want %q", adif.HeaderSection.ProgramVersion, "0.0.1")
	}
	if adif.HeaderSection.CreatedTimestamp != "20250508T120000Z" {
		t.Fatalf("CreatedTimestamp = %q, want %q", adif.HeaderSection.CreatedTimestamp, "20250508T120000Z")
	}

	// Records
	if len(adif.Records) != 2 {
		t.Fatalf("got %d records, want 2", len(adif.Records))
	}

	r0 := adif.Records[0]
	if r0.Call != "M0CMC" {
		t.Fatalf("r0.Call = %q, want %q", r0.Call, "M0CMC")
	}
	if r0.Band != "40m" {
		t.Fatalf("r0.Band = %q, want %q", r0.Band, "40m")
	}
	if r0.Mode != "SSB" {
		t.Fatalf("r0.Mode = %q, want %q", r0.Mode, "SSB")
	}
	if r0.Freq != "7.050" {
		t.Fatalf("r0.Freq = %q, want %q", r0.Freq, "7.050")
	}
	if r0.QsoDate != "20250508" {
		t.Fatalf("r0.QsoDate = %q, want %q", r0.QsoDate, "20250508")
	}
	if r0.TimeOn != "0845" {
		t.Fatalf("r0.TimeOn = %q, want %q", r0.TimeOn, "0845")
	}
	if r0.RstSent != "59" {
		t.Fatalf("r0.RstSent = %q, want %q", r0.RstSent, "59")
	}
	if r0.StationCallsign != "G4ABC" {
		t.Fatalf("r0.StationCallsign = %q, want %q", r0.StationCallsign, "G4ABC")
	}

	r1 := adif.Records[1]
	if r1.Call != "DL1ABC" {
		t.Fatalf("r1.Call = %q, want %q", r1.Call, "DL1ABC")
	}
	if r1.Mode != "CW" {
		t.Fatalf("r1.Mode = %q, want %q", r1.Mode, "CW")
	}
}

