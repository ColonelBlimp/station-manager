package adif

import (
	"bytes"
	"fmt"
	"reflect"
	"strconv"
	"strings"
	"time"
)

func (r *Record) String() string {
	return parseToAdifString(r)
}

func (h *HeaderSection) String() string {
	ts := h.CreatedTimestamp
	if ts == emptyString {
		ts = time.Now().UTC().Format("20060102150405")
	}
	ver := h.ADIFVer
	if ver == emptyString {
		ver = Version
	}
	pid := h.ProgramID
	if pid == emptyString {
		pid = ProgramID
	}
	pver := h.ProgramVersion
	if pver == emptyString {
		pver = ProgramVersion
	}
	txt := "#\n# Generated by Station Manager\n#\n"
	return fmt.Sprintf(
		"%s\n<ADIF_VER:%d>%s\n<CREATED_TIMESTAMP:%d>%s\n<PROGRAMID:%d>%s\n<PROGRAMVERSION:%d>%s\n%s\n%s\n%s\n%s\n%s\n%s\n\n",
		txt,
		len(ver),
		ver,
		len(ts),
		ts,
		len(pid),
		pid,
		len(pver),
		pver,
		UserDefQslWanted,
		UserDefFwrdByEmailStatus,
		UserDefFwrdByEmailDate,
		UserDefQsoUploadStatus,
		UserDefQsoUploadDate,
		EohStr,
	)
}

func (a *Adif) String() string {
	var buf bytes.Buffer
	buf.WriteString(a.HeaderSection.String())
	for _, record := range a.Records {
		buf.WriteString(record.String())
	}
	return buf.String()
}

func parseToAdifString(obj any) string {
	var buf bytes.Buffer
	var parser func(v reflect.Value)

	parser = func(v reflect.Value) {
		for i := 0; i < v.NumField(); i++ {
			field := v.Field(i)
			if field.Kind() == reflect.Ptr {
				field = field.Elem()
			}

			if field.Kind() == reflect.Struct {
				parser(field)
				continue
			}

			if field.Kind() == reflect.String && field.String() != emptyString {
				fieldTag := v.Type().Field(i).Tag
				// Prefer explicit ADIF mapping for adif module structs; fallback to json for embedded types
				tag := fieldTag.Get("adif")
				if tag == emptyString || tag == "-" {
					tag = fieldTag.Get(JsonStructTag)
				}
				tag = strings.TrimSuffix(tag, ",omitempty")
				if tag == emptyString || tag == "-" {
					continue
				}
				// The ADIF DXCC field is the numeric DXCC entity code
				// (e.g. 291). A non-numeric value (such as a DXCC prefix)
				// makes uploaders like QRZ classify the record as
				// NON-DXCC, so drop it rather than emit garbage.
				if strings.EqualFold(tag, "dxcc") && !isAsciiDigits(field.String()) {
					continue
				}
				buf.WriteString(formatField(tag, field.String()))
			}
		}
	}

	parser(reflect.ValueOf(obj).Elem())
	buf.WriteString(EorStr)
	buf.WriteString(NewLineStr)

	return buf.String()
}

// isAsciiDigits reports whether s is non-empty and composed solely of
// ASCII digits 0-9 — the shape required of a numeric ADIF field value.
func isAsciiDigits(s string) bool {
	if s == emptyString {
		return false
	}
	for _, r := range s {
		if r < '0' || r > '9' {
			return false
		}
	}
	return true
}

func formatField(tagName string, value string) string {
	tagName = strings.ToUpper(tagName)

	// Special formatting required for certain fields by the ADIF standard.
	switch tagName {
	case "FREQ", "FREQ_RX":
		value = hzToMHz(value)
	case "QSO_DATE", "QSO_DATE_OFF", "QSLRDATE", "QSLSDATE":
		value = strings.ReplaceAll(value, DashStr, emptyString)
	case "TIME_ON", "TIME_OFF":
		value = strings.ReplaceAll(value, ColonStr, emptyString)
	}

	return fmt.Sprintf(elementFormat, tagName, len(value), value)
}

// hzToMHz converts a raw integer Hz frequency string (7 or 8 digits) to an MHz string.
// Example: "14310000" -> "14.310", "7050000" -> "7.050"
// Values that already contain a decimal point are returned unchanged.
func hzToMHz(s string) string {
	if strings.ContainsRune(s, '.') {
		return s
	}
	if len(s) < 7 || len(s) > 8 {
		return s
	}
	f, err := strconv.ParseFloat(s, 64)
	if err != nil {
		return s
	}
	return fmt.Sprintf("%.3f", f/1000000.0)
}
